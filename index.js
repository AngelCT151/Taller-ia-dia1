"¿Qué es un compromiso y por qué es importante?"
// Un compromiso es una promesa o acuerdo para hacer algo en el futuro. 
// Es importante porque establece expectativas claras, fomenta la responsabilidad y ayuda a construir confianza entre las partes involucradas. 
// Cumplir con los compromisos demuestra integridad y profesionalismo.

"¿Cuál es la diferencia entre git add y git commit?"
// git add se utiliza para agregar cambios en los archivos al área de preparación (staging area) antes de confirmarlos. 
// git commit, por otro lado, se utiliza para guardar esos cambios preparados en el repositorio local con un mensaje descriptivo. 
// En resumen, git add prepara los cambios y git commit los guarda permanentemente en el historial del proyecto.

"Explícame qué hace el comando git push"
// El comando git push se utiliza para subir los cambios confirmados (commits) 
// desde el repositorio local a un repositorio remoto, como GitHub o GitLab. Esto permite compartir los cambios con otros colaboradores y mantener
// el repositorio remoto actualizado con las últimas modificaciones realizadas en el proyecto.